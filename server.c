#define PORT 3490
#define BACKLOG 10
// #define k_max_msg 4096
const size_t k_max_msg = 32 << 20;
const size_t k_max_args = 200 * 1000;

// -------------------------------------------------------------------------------------
// HELPERS -----------------------------------------------------------------------------

static void msg(const char *msg) {
    fprintf(stderr, "%s\n", msg);
}

static void msg_errno(const char *msg) {
    fprintf(stderr, "[errno:%d] %s\n", errno, msg);
}

static void die(const char *msg) {
    fprintf(stderr, "[%d] %s\n", errno, msg);
    abort();
}

static void fd_set_nb(int fd) {
    errno = 0;
    int flags = fcntl(fd, F_GETFL, 0);
    if (errno) {
        die("fcntl error");
        return;
    }

    flags |= O_NONBLOCK;

    errno = 0;
    (void)fcntl(fd, F_SETFL, flags);
    if (errno) {
        die("fcntl error");
    }
}

// -------------------------------------------------------------------------------------
// VECTOR ------------------------------------------------------------------------------

// a growable byte buffer, replaces std::vector<uint8_t>
typedef struct {
    uint8_t *buffer_begin;
    uint8_t *buffer_end;
    uint8_t *data_begin;
    uint8_t *data_end;
} Buffer;

static void buf_init(Buffer *buf) {
    buf->buffer_begin = NULL;
    buf->buffer_end = NULL;
    buf->data_begin = NULL;
    buf->data_end = NULL;
}

static void buf_free(Buffer *buf) {
    free(buf->buffer_begin);
    buf->buffer_begin = NULL;
    buf->buffer_end = NULL;
    buf->data_begin = NULL;
    buf->data_end = NULL;
}

static size_t buf_len(const Buffer *buf) {
    return (size_t)(buf->data_end - buf->data_begin);
}

static size_t buf_cap(const Buffer *buf) {
    return (size_t)(buf->buffer_end - buf->buffer_begin);
}

// remove from the front: just advance a pointer, no data movement
static void buf_consume(Buffer *buf, size_t n) {
    assert(n <= buf_len(buf));
    buf->data_begin += n;
    if (buf->data_begin == buf->data_end) {
        // fully drained: reset to the start so future appends get max space
        buf->data_begin = buf->buffer_begin;
        buf->data_end = buf->buffer_begin;
    }
}

// append to the back
static void buf_append(Buffer *buf, const uint8_t *data, size_t len) {
    size_t used = buf_len(buf);
    size_t tail_space = (size_t)(buf->buffer_end - buf->data_end);

    if (tail_space < len) {
        size_t front_space = (size_t)(buf->data_begin - buf->buffer_begin);
        if (front_space + tail_space >= len) {
            // enough total free space: just slide existing data to the front
            memmove(buf->buffer_begin, buf->data_begin, used);
        } else {
            // not enough room even after compacting: grow the allocation
            size_t new_cap = buf_cap(buf) ? buf_cap(buf) * 2 : 64;
            while (new_cap < used + len) {
                new_cap *= 2;
            }
            uint8_t *new_buf = (uint8_t *)malloc(new_cap);
            if (!new_buf) {
                die("malloc error");
            }
            memcpy(new_buf, buf->data_begin, used);  // compact while copying
            free(buf->buffer_begin);
            buf->buffer_begin = new_buf;
            buf->buffer_end = new_buf + new_cap;
        }
        buf->data_begin = buf->buffer_begin;
        buf->data_end = buf->buffer_begin + used;
    }

    memcpy(buf->data_end, data, len);
    buf->data_end += len;
}

// -------------------------------------------------------------------------------------
// CONN --------------------------------------------------------------------------------

typedef struct Conn {
    int fd;
    // application's intention, for the event loop
    bool want_read;
    bool want_write;
    bool want_close;
    // buffered input and output
    Buffer incoming;  // data to be parsed by the application
    Buffer outgoing;  // responses generated by the application
} Conn;

// application callback when the listening socket is ready
static Conn *handle_accept(int fd) {
    // accept
    struct sockaddr_in client_addr = {0};
    socklen_t addrlen = sizeof(client_addr);
    int connfd = accept(fd, (struct sockaddr *)&client_addr, &addrlen);
    if (connfd < 0) {
        msg_errno("accept() error");
        return NULL;
    }
    uint32_t ip = client_addr.sin_addr.s_addr;
    fprintf(stderr, "new client from %u.%u.%u.%u:%u\n",
        ip & 255, (ip >> 8) & 255, (ip >> 16) & 255, ip >> 24,
        ntohs(client_addr.sin_port)
    );

    // set the new connection fd to nonblocking mode
    fd_set_nb(connfd);

    // create a `struct Conn`
    Conn *conn = (Conn *)malloc(sizeof(Conn));
    memset(conn, 0, sizeof(Conn));
    conn->fd = connfd;
    conn->want_read = true;
    buf_init(&conn->incoming);
    buf_init(&conn->outgoing);
    return conn;
}

// -------------------------------------------------------------------------------------
// STR ---------------------------------------------------------------------------------

// a non-owning view into someone else's bytes (replaces std::string in cmd parsing)
typedef struct Str {
    const uint8_t *data;
    size_t len;
} Str;

// growable array of Str, replaces std::vector<std::string> cmd
typedef struct StrList {
    Str *items;
    size_t len;
    size_t cap;
} StrList;

static void strlist_init(StrList *list) {
    list->items = NULL;
    list->len = 0;
    list->cap = 0;
}

static void strlist_push(StrList *list, Str s) {
    if (list->len == list->cap) {
        list->cap = list->cap ? list->cap * 2 : 8;
        list->items = (Str *)realloc(list->items, list->cap * sizeof(Str));
        if (!list->items) {
            die("realloc error");
        }
    }
    list->items[list->len++] = s;
}

static void strlist_free(StrList *list) {
    free(list->items);
    list->items = NULL;
    list->len = 0;
    list->cap = 0;
}

static bool str_eq(const Str *s, const char *lit) {
    size_t lit_len = strlen(lit);
    return s->len == lit_len && memcmp(s->data, lit, lit_len) == 0;
}

// -------------------------------------------------------------------------------------
// parsing helpers (equivalent of read_u32/read_str/parse_req)
// -------------------------------------------------------------------------------------

static bool read_u32(const uint8_t **cur, const uint8_t *end, uint32_t *out) {
    if (*cur + 4 > end) {
        return false;
    }
    memcpy(out, *cur, 4);
    *cur += 4;
    return true;
}

static bool read_str(const uint8_t **cur, const uint8_t *end, size_t n, Str *out) {
    if (*cur + n > end) {
        return false;
    }
    out->data = *cur;   // no copy: points into the caller's buffer
    out->len = n;
    *cur += n;
    return true;
}

// +------+-----+------+-----+------+-----+-----+------+
// | nstr | len | str1 | len | str2 | ... | len | strn |
// +------+-----+------+-----+------+-----+-----+------+
static int32_t parse_req(const uint8_t *data, size_t size, StrList *out) {
    const uint8_t *end = data + size;
    uint32_t nstr = 0;
    if (!read_u32(&data, end, &nstr)) {
        return -1;
    }
    if (nstr > k_max_args) {
        return -1;  // safety limit
    }

    while (out->len < nstr) {
        uint32_t len = 0;
        if (!read_u32(&data, end, &len)) {
            return -1;
        }
        Str s;
        if (!read_str(&data, end, len, &s)) {
            return -1;
        }
        strlist_push(out, s);
    }
    if (data != end) {
        return -1;  // trailing garbage
    }
    return 0;
}

